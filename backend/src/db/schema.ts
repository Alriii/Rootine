
// Purpose: Describe the PostgreSQL tables and columns that Drizzle uses in this application.
// Meaning: This is the database blueprint; it does not itself create or delete database records.
import {
  pgTable,
  pgEnum,
  uuid,
  text,
  boolean,
  timestamp,
  index,
} from "drizzle-orm/pg-core";

// Purpose: List the account roles the application supports.
// Meaning: For now, every account has the USER role; an enum restricts values to this list.
export const role = pgEnum("Role", ["USER"]);

// Purpose: List the kinds of tokens the application may store.
// Meaning: REFRESH is for keeping a session active; EMAIL_VERIFY is reserved for email verification.
export const tokenType = pgEnum("TokenType", [
  "REFRESH",
  "EMAIL_VERIFY",
  "PASSWORD_RESET",
]);

// Purpose: Define the columns and rules for a user account.
// Meaning: notNull means a value is required; unique prevents two accounts from sharing an email.
export const users = pgTable("users", {
  // Purpose: Give each account a unique identifier generated by PostgreSQL.
  id: uuid("id")
    .primaryKey()
    .defaultRandom(),

  // Purpose: Store the account holder's name.
  name: text("name")
    .notNull(),

  // Purpose: Store the sign-in email and require it to be unique.
  email: text("email")
    .notNull()
    .unique(),

  // Purpose: Store only the password hash, never the original password.
  passwordHash: text("password_hash")
    .notNull(),

  // Purpose: Assign the default account role when one is not supplied.
  role: role("role")
    .default("USER")
    .notNull(),

  // Purpose: Store the phone number and the separate country calling code.
  phoneNumber: text("phone_number")
    .notNull(),

  countryCode: text("country_code")
    .notNull(),

  // Purpose: Store the user's city.
  city: text("city")
    .notNull(),

    // Purpose: Track whether the user's email has been verified.
    emailVerified: boolean("email_verified")
      .default(false)
      .notNull(),

    // Purpose: Record when the account was created.
  createdAt: timestamp("created_at", {
    withTimezone: true,
  })
    .notNull()
    .defaultNow(),

  // Purpose: Record when the account was last changed.
  // Meaning: Drizzle updates this timestamp when an update is made through the ORM.
  updatedAt: timestamp("updated_at", {
    withTimezone: true,
  })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
});

// Purpose: Define stored tokens associated with user accounts.
// Meaning: The table supports refresh/email-verification token data, although those flows still need implementation.
export const tokens = pgTable("token", {
  // Purpose: Give each token record a unique identifier.
  id: uuid("id")
    .primaryKey()
    .defaultRandom(),

  // Purpose: Identify what the stored token is used for.
  type: tokenType("type")
    .notNull(),

  // Purpose: Store the token value and prevent duplicates.
  token: text("token")
    .unique()
    .notNull(),

  // Purpose: Record when the token stops being valid.
  expiresAt: timestamp("expires_at", {
    withTimezone: true,
    mode: "string",
  })
    .notNull(),

  // Purpose: Record when this token record was created.
  createdAt: timestamp("created_at", {
    withTimezone: true,
    mode: "string",
  })
    .notNull()
    .defaultNow(),

  // Purpose: Record when a token has been used, if applicable.
  consumedAt: timestamp("consumed_at", {
    withTimezone: true,
    mode: "string",
  }),

  // Purpose: Record when a token has been invalidated, if applicable.
  revokedAt: timestamp("revoked_at", {
    withTimezone: true,
    mode: "string",
  }),

  // Purpose: Link this token to its owner; deleting the user deletes their tokens.
  userId: uuid("user_id")
    .notNull()
    .references(() => users.id, {
      onDelete: "cascade",
    }),
}, (table) => [
  // Purpose: Make searches by user and token type faster.
  index("token_owner_type_idx").on(
    table.userId,
    table.type,
  ),
]);