// Purpose: Describe the PostgreSQL tables and columns that Drizzle uses in this application.
// Meaning: This is the database blueprint; it does not itself create or delete database records.
import {
  pgTable,
  pgEnum,
  uuid,
  text,
  boolean,
  timestamp,
  index,
  integer,
  jsonb,
  uniqueIndex,
} from "drizzle-orm/pg-core";

// Purpose: List the account roles the application supports.
// Meaning: For now, every account has the USER role; an enum restricts values to this list.
export const role = pgEnum("Role", ["USER"]);

// Purpose: List the kinds of tokens the application may store.
// Meaning: REFRESH is for keeping a session active; EMAIL_VERIFY is reserved for email verification.
export const tokenType = pgEnum("TokenType", [
  "REFRESH",
  "EMAIL_VERIFY",
  "PASSWORD_RESET",
]);

// Purpose: List the frequency modes supported for recurring tasks.
export const taskFrequency = pgEnum("TaskFrequency", [
  "DAILY",
  "SPECIFIC_DAYS",
  "TIMES_PER_WEEK",
]);

// Purpose: TypeScript type definition for schedule configuration JSON.
export type TaskScheduleConfig = {
  daysOfWeek?: number[]; // e.g. [1, 2, 3, 4, 5] (1=Monday ... 7=Sunday)
  targetPerDay?: number; // e.g. 8 (for habits like 8 glasses of water)
  targetPerWeek?: number; // e.g. 3 (times per week)
};

// Purpose: Define the columns and rules for a user account.
// Meaning: notNull means a value is required; unique prevents two accounts from sharing an email.
export const users = pgTable("users", {
  // Purpose: Give each account a unique identifier generated by PostgreSQL.
  id: uuid("id")
    .primaryKey()
    .defaultRandom(),

  // Purpose: Store the account holder's name.
  name: text("name")
    .notNull(),

  // Purpose: Store the sign-in email and require it to be unique.
  email: text("email")
    .notNull()
    .unique(),

  // Purpose: Store only the password hash, never the original password.
  passwordHash: text("password_hash")
    .notNull(),

  // Purpose: Assign the default account role when one is not supplied.
  role: role("role")
    .default("USER")
    .notNull(),

  // Purpose: Store the phone number and the separate country calling code.
  phoneNumber: text("phone_number")
    .notNull(),

  countryCode: text("country_code")
    .notNull(),

  // Purpose: Store the user's city.
  city: text("city")
    .notNull(),

  // Purpose: Store user timezone for accurate streak and today-schedule calculations.
  timezone: text("timezone")
    .default("Asia/Manila")
    .notNull(),

  // Purpose: Track whether the user's email has been verified.
  emailVerified: boolean("email_verified")
    .default(false)
    .notNull(),

  // Purpose: Record when the account was created.
  createdAt: timestamp("created_at", {
    withTimezone: true,
  })
    .notNull()
    .defaultNow(),

  // Purpose: Record when the account was last changed.
  // Meaning: Drizzle updates this timestamp when an update is made through the ORM.
  updatedAt: timestamp("updated_at", {
    withTimezone: true,
  })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
});

// Purpose: Define stored tokens associated with user accounts.
// Meaning: The table supports refresh/email-verification token data.
export const tokens = pgTable("token", {
  // Purpose: Give each token record a unique identifier.
  id: uuid("id")
    .primaryKey()
    .defaultRandom(),

  // Purpose: Identify what the stored token is used for.
  type: tokenType("type")
    .notNull(),

  // Purpose: Store the token value and prevent duplicates.
  token: text("token")
    .unique()
    .notNull(),

  // Purpose: Record when the token stops being valid.
  expiresAt: timestamp("expires_at", {
    withTimezone: true,
    mode: "string",
  })
    .notNull(),

  // Purpose: Record when this token record was created.
  createdAt: timestamp("created_at", {
    withTimezone: true,
    mode: "string",
  })
    .notNull()
    .defaultNow(),

  // Purpose: Record when a token has been used, if applicable.
  consumedAt: timestamp("consumed_at", {
    withTimezone: true,
    mode: "string",
  }),

  // Purpose: Record when a token has been invalidated, if applicable.
  revokedAt: timestamp("revoked_at", {
    withTimezone: true,
    mode: "string",
  }),

  // Purpose: Link this token to its owner; deleting the user deletes their tokens.
  userId: uuid("user_id")
    .notNull()
    .references(() => users.id, {
      onDelete: "cascade",
    }),
}, (table) => [
  // Purpose: Make searches by user and token type faster.
  index("token_owner_type_idx").on(
    table.userId,
    table.type,
  ),
]);

// Purpose: Define recurring tasks / habits owned by users.
export const tasks = pgTable("tasks", {
  id: uuid("id")
    .primaryKey()
    .defaultRandom(),

  userId: uuid("user_id")
    .notNull()
    .references(() => users.id, {
      onDelete: "cascade",
    }),

  title: text("title")
    .notNull(),

  description: text("description"),

  frequency: taskFrequency("frequency")
    .default("DAILY")
    .notNull(),

  scheduleConfig: jsonb("schedule_config").$type<TaskScheduleConfig>(),

  preferredTimeWindow: text("preferred_time_window"), // e.g., 'MORNING', 'AFTERNOON', 'EVENING', 'ANYTIME'

  color: text("color"),

  icon: text("icon"),

  position: integer("position")
    .default(0)
    .notNull(),

  isArchived: boolean("is_archived")
    .default(false)
    .notNull(),

  deletedAt: timestamp("deleted_at", {
    withTimezone: true,
  }),

  // Email Reminder Settings
  reminderEnabled: boolean("reminder_enabled")
    .default(false)
    .notNull(),

  reminderTime: text("reminder_time"), // e.g. "08:30" (24-hour HH:mm)

  reminderIntervalHours: integer("reminder_interval_hours")
    .default(1)
    .notNull(), // Repeat every N hours until completed

  maxDailyReminders: integer("max_daily_reminders")
    .default(4)
    .notNull(), // Max reminders per day to prevent spam

  lastRemindedAt: timestamp("last_reminded_at", {
    withTimezone: true,
  }),

  reminderCountToday: integer("reminder_count_today")
    .default(0)
    .notNull(),

  createdAt: timestamp("created_at", {
    withTimezone: true,
  })
    .notNull()
    .defaultNow(),

  updatedAt: timestamp("updated_at", {
    withTimezone: true,
  })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
}, (table) => [
  index("tasks_user_active_idx").on(
    table.userId,
    table.deletedAt,
    table.isArchived,
  ),
  index("tasks_user_position_idx").on(
    table.userId,
    table.position,
  ),
  index("tasks_reminder_active_idx").on(
    table.reminderEnabled,
    table.isArchived,
    table.deletedAt,
  ),
]);

// Purpose: Track daily completions and logs for tasks.
export const taskCompletions = pgTable("task_completions", {
  id: uuid("id")
    .primaryKey()
    .defaultRandom(),

  taskId: uuid("task_id")
    .notNull()
    .references(() => tasks.id, {
      onDelete: "cascade",
    }),

  userId: uuid("user_id")
    .notNull()
    .references(() => users.id, {
      onDelete: "cascade",
    }),

  completedDate: text("completed_date")
    .notNull(), // YYYY-MM-DD in user's timezone

  completedAt: timestamp("completed_at", {
    withTimezone: true,
  })
    .notNull()
    .defaultNow(),

  count: integer("count")
    .default(1)
    .notNull(), // For habits completed multiple times a day

  note: text("note"),

  mood: integer("mood"), // Optional mood score 1-5

  createdAt: timestamp("created_at", {
    withTimezone: true,
  })
    .notNull()
    .defaultNow(),
}, (table) => [
  uniqueIndex("task_completions_task_date_uidx").on(
    table.taskId,
    table.completedDate,
  ),
  index("task_completions_user_date_idx").on(
    table.userId,
    table.completedDate,
  ),
]);
